import { createHash } from 'node:crypto';
import { execFile } from 'node:child_process';
import {
  existsSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  renameSync,
  rmSync,
  statSync,
  writeFileSync,
} from 'node:fs';
import { delimiter, join, resolve, sep } from 'node:path';

import { ProtocolError } from '../../common/protocol.js';
import { boundsOf, expand, normalizeRecipe, walk } from './grow.js';
import { cropPngTopLeft } from './png-crop.js';

/**
 * Renders a PNG snapshot of a `grow` organism, by driving an ordinary
 * installed browser in headless mode rather than a 3D engine of its own.
 *
 * `grow` already returns a skeleton in milliseconds; what it does not do is
 * turn that into a picture, and `alpha.render` cannot do it either — that
 * handler drives Blender's Python API against `generate.py`, a script that
 * lives outside this repository and knows nothing about L-systems. Feeding a
 * skeleton to it would mean inventing a richer interface on the Python side
 * unilaterally, which `grow.js`'s own header says is deliberately not done
 * here. So this handler draws the skeleton itself: project the nodes to 2D,
 * stroke the edges, and let a real browser turn that into a screenshot. No
 * WebGL, no 3D library, vendored or otherwise — a skeleton is lines, and
 * `<canvas>` 2D already draws lines. That also keeps this repo's "Node
 * standard library only" rule honest one door further out: the browser is an
 * external program, exactly like `alpha-render.js`'s Blender, but nothing it
 * runs was written by anyone but this handler.
 *
 * Same split as `alpha.render`: the image stays on the machine that made it,
 * and the result carries the recipe plus what landed and how big it is.
 *
 * This is an external-program handler, so it follows the rules
 * `alpha-coordination.js` set: a pinned executable, a pinned output
 * directory that must resolve inside a configured root, and arguments passed
 * to `execFile` as an argv array. There is no script to pin here — the page
 * it renders is generated by this handler, not read from disk — so unlike
 * `alpha-render.js` there is no `ALPHA_GROW_RENDER_SCRIPT`.
 *
 * It is NOT registered by default. Enable it on a machine that has a browser
 * installed with ALPHA_EXTRA_HANDLERS=alpha-grow-render.
 *
 * Configuration:
 *   ALPHA_GROW_RENDER_ROOT     Directory renders are written under (required)
 *   ALPHA_GROW_RENDER_OUTPUT   Where finished images land, relative to root.
 *                              Defaults to `output`
 *   ALPHA_GROW_RENDER_BROWSER  Browser executable. Unset probes common
 *                              Chromium/Chrome/Edge binary names in turn
 *   ALPHA_GROW_RENDER_TIMEOUT_MS  Hard ceiling on one render. Defaults to
 *                              30 seconds — this is a canvas screenshot, not
 *                              a path-traced frame, so it should never come
 *                              close
 *
 * Payload: any `grow` recipe field (`preset`, `axiom`, `rules`, `iterations`,
 * `angle`, `roll`, `step`, `taper`, `jitter`, `radius`, `seed`,
 * `maxSegments` — see grow.js), plus:
 *   width, height   Image size in pixels, 64-2048 each way. Default 800x600
 *   background      A "#rrggbb" colour. Default "#eef2ec"
 *
 * The screenshot Chromium actually takes is taller than `height` and gets
 * cropped back down before this returns one — see WINDOW_HEIGHT_MARGIN and
 * `png-crop.js` for why.
 */

export const type = 'alpha.grow-render';

export const description =
  'Renders a PNG snapshot of a grow organism in a headless browser and returns the recipe that reproduces it.';

const DEFAULT_OUTPUT = 'output';
const DEFAULT_TIMEOUT_MS = 30_000;

// Chromium's headless `--screenshot` writes a bitmap the size of
// `--window-size`, but the page's real content viewport is shorter than that
// — verified on Chromium 141 at roughly 85-90px, constant regardless of the
// requested height, present under both `--headless` and `--headless=new`.
// Asking for a window this much taller than the picture wanted, and cropping
// the result back down in `png-crop.js`, works around it without depending
// on the exact deficit: it only has to be smaller than this margin.
const WINDOW_HEIGHT_MARGIN = 300;

// Chromium screenshots at these sizes without incident; past a few thousand
// pixels a screenshot stops being "a quick look at the organism" and starts
// being a render job with none of the safeguards `alpha.render` has for one.
const DIMENSION_LIMITS = { min: 64, max: 2048 };
const DEFAULT_WIDTH = 800;
const DEFAULT_HEIGHT = 600;
const DEFAULT_BACKGROUND = '#eef2ec';
const HEX_COLOR = /^#[0-9a-fA-F]{6}$/;

// Probed in order when ALPHA_GROW_RENDER_BROWSER is unset. Every one of these
// supports --headless and --screenshot the same way, so the first one found
// is as good as any other.
const DEFAULT_BROWSER_CANDIDATES = [
  'chromium',
  'chromium-browser',
  'google-chrome',
  'google-chrome-stable',
  'microsoft-edge',
  'microsoft-edge-stable',
  'msedge',
  'chrome',
];

/** Reads an environment variable, treating blank as unset rather than as "". */
function configured(name, fallback) {
  const raw = process.env[name];
  return raw === undefined || raw.trim() === '' ? fallback : raw;
}

function requireRoot() {
  const root = process.env.ALPHA_GROW_RENDER_ROOT;
  if (!root) {
    throw new ProtocolError(
      'ALPHA_GROW_RENDER_ROOT is not set on this agent, so there is nowhere to write a render',
      { status: 500, code: 'not_configured' },
    );
  }
  const resolved = resolve(root);
  if (!existsSync(resolved)) {
    throw new ProtocolError(`ALPHA_GROW_RENDER_ROOT does not exist: ${resolved}`, {
      status: 500,
      code: 'not_configured',
    });
  }
  return resolved;
}

/** Resolves a configured path and refuses anything that leaves the root. */
function insideRoot(root, relative, label) {
  const resolved = resolve(root, relative);
  if (resolved !== root && !resolved.startsWith(root + sep)) {
    throw new ProtocolError(`${label} must live inside ALPHA_GROW_RENDER_ROOT`, {
      status: 500,
      code: 'not_configured',
    });
  }
  return resolved;
}

/**
 * The directory finished images are filed under, resolved and bounds-checked.
 * Mirrors `alpha-render.js`'s `resolveOutputDir()` for the same reason that
 * one exists: so nothing else that wants to know where renders live has to
 * keep a second copy of the rule.
 */
export function resolveOutputDir() {
  const root = requireRoot();
  return {
    root,
    outputDir: insideRoot(root, configured('ALPHA_GROW_RENDER_OUTPUT', DEFAULT_OUTPUT), 'ALPHA_GROW_RENDER_OUTPUT'),
  };
}

export const STAGING_PREFIX = '.grow-render-';

/**
 * Where a command would be found, or null. Identical to `alpha-render.js`'s
 * helper of the same job — PATH resolution plus PATHEXT on Windows, because
 * `execFile` resolves a bare name against PATH and the availability check has
 * to agree or a browser that is genuinely installed reads as missing.
 */
function resolveExecutable(command) {
  if (command.includes('/') || command.includes(sep)) {
    return existsSync(command) ? command : null;
  }
  const extensions =
    process.platform === 'win32'
      ? (process.env.PATHEXT ?? '.EXE;.CMD;.BAT;.COM').split(';').filter(Boolean)
      : [''];
  for (const directory of (process.env.PATH ?? '').split(delimiter)) {
    if (!directory) continue;
    for (const extension of extensions) {
      const candidate = join(directory, command + extension);
      if (existsSync(candidate)) return candidate;
    }
  }
  return null;
}

/**
 * The browser this render would run, or null if none of the candidates
 * exist. Exported so `available()` and `run()` ask exactly the same
 * question the same way — a machine that passes the check and then fails to
 * launch the browser is the failure mode this pattern exists to prevent.
 */
export function resolveBrowser() {
  const explicit = process.env.ALPHA_GROW_RENDER_BROWSER;
  if (explicit && explicit.trim() !== '') {
    const path = resolveExecutable(explicit.trim());
    return path ? { path, name: explicit.trim() } : null;
  }
  for (const name of DEFAULT_BROWSER_CANDIDATES) {
    const path = resolveExecutable(name);
    if (path) return { path, name };
  }
  return null;
}

function num(value, field, { min, max, fallback }) {
  if (value === undefined || value === null) return fallback;
  if (typeof value !== 'number' || !Number.isFinite(value)) {
    throw new ProtocolError(`"${field}" must be a finite number`);
  }
  if (value < min || value > max) {
    throw new ProtocolError(`"${field}" must be between ${min} and ${max}`);
  }
  return value;
}

function validateBackground(value) {
  if (value === undefined || value === null) return DEFAULT_BACKGROUND;
  if (typeof value !== 'string' || !HEX_COLOR.test(value)) {
    throw new ProtocolError(`"background" must be a "#rrggbb" colour (got ${JSON.stringify(value)})`);
  }
  return value;
}

/**
 * A short, deterministic name for what this recipe draws.
 *
 * A preset name plus a seed is not always enough to tell two renders apart —
 * a custom axiom and a preset's axiom can share the name "custom", and two
 * custom recipes at the same seed are two different organisms. Hashing the
 * whole normalized recipe (everything that affects the geometry, not the
 * render's own width/height/background) means same recipe -> same file, and
 * different recipe -> a different one, which is the same "re-run replaces
 * its own output, nothing else collides with it" guarantee `alpha-render.js`
 * gets for free from `species` alone.
 */
function recipeHash(recipe) {
  const { format, ...geometry } = recipe;
  return createHash('sha256').update(JSON.stringify(geometry)).digest('hex').slice(0, 10);
}

/**
 * Bakes a value into a JSON literal safe to embed inside a <script> tag.
 *
 * Nothing reaches this today that isn't already numeric, or a background
 * colour already checked against `HEX_COLOR`, or one of the two fixed
 * `strokeColor` literals below — none of which can contain `<`. But an
 * axiom or a rule body is never far from this function's callers, and the
 * day one of them starts riding along, "cannot contain `</script>`" needs to
 * already be true rather than becoming a fire drill. Escaping every `<` is
 * the same "payload data never reaches a shell" rule the other handlers hold
 * themselves to, just aimed at a browser's script parser instead of a
 * shell's.
 */
function embedJson(value) {
  return JSON.stringify(value).replace(/</g, '\\u003c');
}

/**
 * The self-contained page a render screenshots. It draws the organism with
 * plain <canvas> 2D — a rotate-then-project-then-scale-to-fit, the same
 * three steps any orthographic viewer does — and nothing else runs on the
 * page: no network fetch, no external script, no library. The drawing
 * happens synchronously while the page loads, so by the time the `load`
 * event Chromium's --screenshot waits for fires, the canvas is already the
 * finished picture.
 *
 * Exported so a test can assert directly on the markup `embedJson` produces.
 */
export function renderPage({ nodes, edges, bounds, kind, width, height, background }) {
  const strokeColor = kind === 'animal' ? '#b5533c' : '#3a7d44';
  const data = embedJson({ nodes, edges, bounds, width, height, background, strokeColor });
  return `<!doctype html>
<html>
<head>
<meta charset="utf-8">
<style>
  html, body { margin: 0; padding: 0; overflow: hidden; }
  canvas { display: block; }
</style>
</head>
<body>
<canvas id="c" width="${width}" height="${height}"></canvas>
<script>
(function () {
  var DATA = ${data};
  var canvas = document.getElementById('c');
  var ctx = canvas.getContext('2d');

  ctx.fillStyle = DATA.background;
  ctx.fillRect(0, 0, DATA.width, DATA.height);

  var angleY = Math.PI / 6;
  var angleX = -Math.PI / 7;
  var cosY = Math.cos(angleY), sinY = Math.sin(angleY);
  var cosX = Math.cos(angleX), sinX = Math.sin(angleX);
  var cx = DATA.bounds.center[0], cy = DATA.bounds.center[1], cz = DATA.bounds.center[2];

  var projected = DATA.nodes.map(function (n) {
    var px = n[0] - cx, py = n[1] - cy, pz = n[2] - cz;
    var rx = px * cosY + pz * sinY;
    var rz = -px * sinY + pz * cosY;
    var ry = py * cosX - rz * sinX;
    rz = py * sinX + rz * cosX;
    return [rx, ry, rz];
  });

  if (projected.length === 0) {
    // Nothing grew. An empty canvas is still an honest picture of that.
  } else {
    var minX = Infinity, maxX = -Infinity, minY = Infinity, maxY = -Infinity;
    for (var i = 0; i < projected.length; i += 1) {
      var p = projected[i];
      if (p[0] < minX) minX = p[0];
      if (p[0] > maxX) maxX = p[0];
      if (p[1] < minY) minY = p[1];
      if (p[1] > maxY) maxY = p[1];
    }
    var spanX = Math.max(maxX - minX, 1e-6);
    var spanY = Math.max(maxY - minY, 1e-6);
    var pad = 0.1;
    var scale = Math.min(
      (DATA.width * (1 - 2 * pad)) / spanX,
      (DATA.height * (1 - 2 * pad)) / spanY,
    );
    var midX = (minX + maxX) / 2;
    var midY = (minY + maxY) / 2;
    var screen = projected.map(function (p) {
      return [
        DATA.width / 2 + (p[0] - midX) * scale,
        DATA.height / 2 - (p[1] - midY) * scale,
        p[2],
      ];
    });

    var edges = DATA.edges.slice().sort(function (a, b) {
      var za = (screen[a[0]][2] + screen[a[1]][2]) / 2;
      var zb = (screen[b[0]][2] + screen[b[1]][2]) / 2;
      return za - zb; // back to front
    });

    ctx.strokeStyle = DATA.strokeColor;
    ctx.lineCap = 'round';
    for (var e = 0; e < edges.length; e += 1) {
      var edge = edges[e];
      var a = screen[edge[0]], b = screen[edge[1]];
      // grow.js's own taper ('!') shrinks an edge's radius multiplicatively
      // every iteration, so a deeply tapered tip legitimately rounds to
      // exactly 0 -- "edge[2] || 0.05" read that genuine 0 as "missing" and
      // substituted a radius almost 15x the whole organism's span on a
      // tightly-scaled recipe, filling the canvas solid. The 1px floor two
      // lines down already guarantees a tapered segment stays visible, so
      // there is no missing case left for a fallback to paper over. (No
      // backticks in this comment: it lives inside renderPage()'s own
      // template-literal return value, where one would end the string early.)
      var radius = typeof edge[2] === 'number' ? edge[2] : 0;
      ctx.lineWidth = Math.max(1, radius * scale * 2);
      ctx.beginPath();
      ctx.moveTo(a[0], a[1]);
      ctx.lineTo(b[0], b[1]);
      ctx.stroke();
    }
  }
})();
</script>
</body>
</html>
`;
}

function timeoutMs() {
  const raw = process.env.ALPHA_GROW_RENDER_TIMEOUT_MS;
  if (!raw || raw.trim() === '') return DEFAULT_TIMEOUT_MS;
  const parsed = Number(raw);
  if (!Number.isInteger(parsed) || parsed <= 0) {
    throw new ProtocolError(
      `ALPHA_GROW_RENDER_TIMEOUT_MS must be a positive whole number of milliseconds (got ${raw})`,
      { status: 500, code: 'not_configured' },
    );
  }
  return parsed;
}

/**
 * Builds the argv passed to the browser. Exported so tests can assert on it.
 *
 * `--no-sandbox` is added only when this process is root, because Chromium's
 * own sandbox refuses to start as root and there is no other way to make it
 * happy — every other machine keeps the sandbox. `--disable-dev-shm-usage`
 * is the standard fix for the tiny /dev/shm a lot of containers hand out;
 * without it Chromium can crash on startup for a reason that has nothing to
 * do with this handler. `--virtual-time-budget` bounds how long the browser
 * waits for the page's `load` event before giving up.
 *
 * `windowHeight` is `height` plus `WINDOW_HEIGHT_MARGIN`, not `height`
 * itself — see that constant's comment for why the window has to be asked
 * for taller than the picture it produces.
 */
export function buildArgs({ htmlPath, pngPath, width, height, windowHeight, asRoot }) {
  return [
    ...(asRoot ? ['--no-sandbox'] : []),
    '--headless',
    '--disable-gpu',
    '--disable-dev-shm-usage',
    '--hide-scrollbars',
    '--force-device-scale-factor=1',
    `--window-size=${width},${windowHeight}`,
    '--virtual-time-budget=5000',
    `--screenshot=${pngPath}`,
    `file://${htmlPath}`,
  ];
}

/**
 * Whether this machine can actually render, asked before the agent offers
 * to. Asks exactly what `run()` asks, the same way, and executes nothing —
 * the browser is looked up, not launched. Whether it can actually screenshot
 * a page is not knowable without rendering one, and `run()` still reports
 * that honestly.
 */
export function available() {
  try {
    resolveOutputDir();
  } catch (error) {
    return { ok: false, reason: error.message };
  }

  const browser = resolveBrowser();
  if (!browser) {
    const named = process.env.ALPHA_GROW_RENDER_BROWSER;
    return {
      ok: false,
      reason: named
        ? `browser not found (${named}). Set ALPHA_GROW_RENDER_BROWSER to its path.`
        : `no browser found (tried ${DEFAULT_BROWSER_CANDIDATES.join(', ')}). ` +
          'Set ALPHA_GROW_RENDER_BROWSER to point at one.',
    };
  }
  return { ok: true };
}

export async function run(payload, { signal, log } = {}) {
  const { root, outputDir } = resolveOutputDir();

  const recipe = normalizeRecipe(payload);
  const width = Math.floor(num(payload?.width, 'width', { ...DIMENSION_LIMITS, fallback: DEFAULT_WIDTH }));
  const height = Math.floor(num(payload?.height, 'height', { ...DIMENSION_LIMITS, fallback: DEFAULT_HEIGHT }));
  const background = validateBackground(payload?.background);

  const browser = resolveBrowser();
  if (!browser) {
    throw new ProtocolError(
      'no browser found on this agent. Set ALPHA_GROW_RENDER_BROWSER to one, or run ' +
        '`alpha-admin agents` to confirm this machine still advertises alpha.grow-render.',
      { status: 500, code: 'no_browser' },
    );
  }

  const symbols = expand(recipe, { signal });
  const { nodes, edges } = walk(recipe, symbols, { signal });
  const bounds = boundsOf(nodes);
  const stats = { symbols: symbols.length, nodes: nodes.length, segments: edges.length, bounds };

  mkdirSync(outputDir, { recursive: true });
  const stagingDir = mkdtempSync(resolve(outputDir, STAGING_PREFIX));
  const htmlPath = join(stagingDir, 'organism.html');
  const pngName = `${recipe.name}-seed${recipe.seed}-${recipeHash(recipe)}.png`;
  const pngPath = join(stagingDir, pngName);

  writeFileSync(
    htmlPath,
    renderPage({ nodes, edges, bounds, kind: recipe.kind, width, height, background }),
  );

  const args = buildArgs({
    htmlPath,
    pngPath,
    width,
    height,
    windowHeight: height + WINDOW_HEIGHT_MARGIN,
    asRoot: process.getuid?.() === 0,
  });
  log?.info?.('rendering', { name: recipe.name, seed: recipe.seed, width, height });

  const startedAt = Date.now();
  const { stdout, stderr, code } = await new Promise((resolvePromise, rejectPromise) => {
    execFile(
      browser.path,
      args,
      { cwd: root, signal, timeout: timeoutMs(), maxBuffer: 16 * 1024 * 1024, windowsHide: true },
      (error, out, err) => {
        if (error && error.code === 'ENOENT') {
          rejectPromise(
            new ProtocolError(`browser not found (${browser.path}). Set ALPHA_GROW_RENDER_BROWSER.`, {
              status: 500,
              code: 'no_browser',
            }),
          );
          return;
        }
        if (error && (error.killed || error.signal || error.code === 'ABORT_ERR')) {
          rejectPromise(
            new ProtocolError(
              `browser was killed before it finished (${error.signal ?? error.code}). Either the ` +
                'render outran ALPHA_GROW_RENDER_TIMEOUT_MS, or the task lease expired.',
              { status: 500, code: 'render_killed' },
            ),
          );
          return;
        }
        resolvePromise({ stdout: out ?? '', stderr: err ?? '', code: error?.code ?? 0 });
      },
    );
  });

  if (code !== 0) {
    rmSync(stagingDir, { recursive: true, force: true });
    throw new ProtocolError(
      `browser exited ${code} rendering "${recipe.name}" seed ${recipe.seed}: ${stderr.trim().slice(-1_000)}`,
      { status: 500, code: 'render_failed' },
    );
  }

  if (!existsSync(pngPath) || statSync(pngPath).size === 0) {
    rmSync(stagingDir, { recursive: true, force: true });
    throw new ProtocolError(
      'browser exited 0 but wrote no image. --screenshot should have written one at the given path.',
      { status: 500, code: 'no_image' },
    );
  }

  // The screenshot is windowHeight tall, not height -- see WINDOW_HEIGHT_MARGIN.
  // What is drawn lives entirely in its top `height` rows; the rest is the
  // dead strip that margin exists to absorb, and reporting a PNG with that
  // strip still attached would hand back an image with the organism crammed
  // into part of the frame instead of filling the one that was asked for.
  try {
    writeFileSync(pngPath, cropPngTopLeft(readFileSync(pngPath), width, height));
  } catch (error) {
    rmSync(stagingDir, { recursive: true, force: true });
    throw new ProtocolError(`could not crop the screenshot to ${width}x${height}: ${error.message}`, {
      status: 500,
      code: 'crop_failed',
    });
  }

  const destPath = resolve(outputDir, pngName);
  renameSync(pngPath, destPath);
  const bytes = statSync(destPath).size;
  rmSync(stagingDir, { recursive: true, force: true });

  return {
    recipe,
    stats,
    outputs: [{ name: pngName, path: destPath, bytes }],
    renderedInMs: Date.now() - startedAt,
    stdout: stdout.slice(-4_000),
    stderr: stderr.slice(-4_000),
  };
}
